#!/usr/bin/env node
/**
 * Package-manager authority guard (PORT-GAP-016): npm is authoritative. Repository policy is that
 * package-lock.json is git-ignored and generated locally/in CI by `npm install`, so its absence is not an
 * error. npm is the only package manager: the guard fails on any competing lockfile (yarn.lock,
 * pnpm-lock.yaml, bun.lock, bun.lockb), a package.json whose packageManager field is not npm, or (when a
 * generated package-lock.json is present) one older than lockfileVersion 3.
 */
import { existsSync, readFileSync } from "node:fs";
const pkg = JSON.parse(readFileSync("package.json", "utf8"));
const problems = [];
if (!/^npm@\d+\.\d+\.\d+/.test(pkg.packageManager ?? ""))
  problems.push("package.json packageManager must be npm@<version>.");
if (existsSync("package-lock.json")) {
  if (JSON.parse(readFileSync("package-lock.json", "utf8")).lockfileVersion < 3)
    problems.push("package-lock.json must be lockfileVersion 3.");
} else {
  console.log(
    "NOTE: package-lock.json is absent; it is generated by `npm install` and not committed.",
  );
}
for (const file of ["yarn.lock", "pnpm-lock.yaml", "bun.lock", "bun.lockb"])
  if (existsSync(file)) problems.push(`${file} competes with npm as the package manager.`);
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}
console.log("Package manager OK: npm is authoritative.");
